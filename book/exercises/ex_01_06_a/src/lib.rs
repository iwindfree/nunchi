// 아래 함수는 컴파일되지 않습니다.
//
// 참조를 두 개 받아 그중 하나를 돌려주는데, 컴파일러가 반환값이 어느 쪽에서
// 왔는지 알 수 없습니다. 수명 이름표를 붙여서 알려 주십시오.
//
// 힌트: 1.6장의 "적어야 하는 경우" 를 보십시오.
//       함수 이름 뒤에 <'a> 를 선언하고, 관련된 참조에 'a 를 붙입니다.

/// 두 경로 중 더 깊은 것을 돌려줍니다.
pub fn deeper(a: &str, b: &str) -> &str {
    if a.matches('/').count() >= b.matches('/').count() { a } else { b }
}

/// 접두가 있으면 떼고 없으면 원본을 돌려줍니다.
/// 이 함수는 참조를 하나만 받으므로 표기가 필요 없습니다. 그대로 두십시오.
pub fn strip_node_prefix(id: &str) -> &str {
    id.split_once(':').map(|(_, rest)| rest).unwrap_or(id)
}
