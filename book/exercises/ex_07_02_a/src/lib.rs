//
// 아래 함수는 정상으로 동작합니다. 파일 맨 아래에 테스트 모듈을
// 추가하십시오.
//
// 요구 사항:
//   1. #[cfg(test)] 를 붙인 mod tests 를 만듭니다
//   2. 그 안에서 use super::*; 로 바깥 함수를 가져옵니다
//   3. #[test] 를 붙인 함수를 두 개 이상 작성합니다
//      - 정상 경로를 확인하는 것 하나
//      - 경계 조건을 확인하는 것 하나 (빈 입력)
//
// 왜 같은 파일에 두는가:
//   비공개 함수도 테스트할 수 있고, 코드를 고칠 때 테스트가 바로 옆에
//   있어서 함께 고치게 됩니다.

/// 경로에서 확장자를 꺼냅니다. 없으면 None 입니다.
pub fn extension(path: &str) -> Option<&str> {
    let name = path.rsplit('/').next()?;
    name.rsplit_once('.').map(|(_, ext)| ext)
}

